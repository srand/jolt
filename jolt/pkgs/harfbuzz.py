from jolt import attributes, BooleanParameter, Parameter
from jolt.pkgs import compiler, freetype
from jolt.plugins import cxxinfo, git, meson, pkgconfig
from jolt.tasks import TaskRegistry


@attributes.requires("requires_freetype")
@attributes.requires("requires_git")
@meson.requires()
@pkgconfig.requires()
@cxxinfo.publish(incpaths=["include/harfbuzz"], libraries=["harfbuzz"])
@attributes.requires("requires_compiler")
@attributes.system
class Harfbuzz(meson.Meson):
    """ Text shaping engine """

    name = "harfbuzz"
    version = Parameter("15.0.0", help="HarfBuzz version.")
    shared = BooleanParameter(False, help="Build shared libraries.")
    requires_compiler = ["virtual/compiler/c", "virtual/compiler/cxx"]
    requires_freetype = ["freetype:pic=true,shared={shared}"]
    requires_git = ["git:clean=true,url=https://github.com/harfbuzz/harfbuzz.git,rev={version}"]
    srcdir = "{git[harfbuzz]}"
    options = [
        "cairo=disabled",
        "chafa=disabled",
        "default_library={shared[shared,static]}",
        "docs=disabled",
        "freetype=enabled",
        "glib=disabled",
        "gobject=disabled",
        "icu=disabled",
        "introspection=disabled",
        "tests=disabled",
        "utilities=disabled",
    ]

    def run(self, deps, tools):
        if self.system == "windows":
            # harfbuzz-world.cc, an amalgamation of the sources that isn't
            # installed, is generated by a command with the paths of all
            # sources, which is longer than Windows allows
            with tools.cwd(self.srcdir, "src"):
                tools.replace_in_file(
                    "meson.build",
                    r"(custom_target\('harfbuzz-world\.cc',\s+build_by_default:\s*)true",
                    r"\1false",
                    regex=True)
        super().run(deps, tools)


TaskRegistry.get().add_task_class(Harfbuzz)
